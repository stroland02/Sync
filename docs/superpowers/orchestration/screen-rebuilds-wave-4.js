const BUILD_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['screen', 'reference', 'done', 'isLocked', 'tscClean', 'vitestClean', 'files', 'deleted', 'measurements', 'forCoordinator'],
  properties: {
    screen: { type: 'string' },
    reference: { type: 'string', description: 'the Stitch reference chosen, and one line on why' },
    done: { type: 'string', description: 'what the screen is now, top to bottom' },
    isLocked: { type: 'boolean' },
    tscClean: { type: 'boolean' },
    vitestClean: { type: 'boolean' },
    files: { type: 'array', items: { type: 'string' } },
    testsChanged: { type: 'array', items: { type: 'string' } },
    deleted: { type: 'array', items: { type: 'string' }, description: 'what was removed and why' },
    measurements: { type: 'string', description: 'live DOM numbers at BOTH resolutions' },
    refusals: { type: 'array', items: { type: 'string' }, description: 'anything in the reference refused on honesty grounds' },
    blocked: { type: 'array', items: { type: 'string' } },
    forCoordinator: { type: 'string', description: 'cross-directory work FIRST, then rulings taken' },
  },
}

const VERDICT_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['refuted', 'findings'],
  properties: {
    refuted: { type: 'boolean' },
    findings: { type: 'array', items: { type: 'string' } },
    gatesPassed: { type: 'boolean' },
  },
}

